import Foundation
import os

/// A reference to a document within a Duality View (DV) collection.
///
/// Duality views provide a unified interface for accessing both document and
/// relational data. This type exposes CRUD operations, snapshot retrieval, and
/// real-time listeners for DV documents.
///
/// Notes:
/// - DV paths are at most two segments: `["dv_name"]` or `["dv_name", "OID"]`.
/// - While the DV endpoints differ from standard collections, this class bridges
///   to `DocumentReference` when building `DocumentSnapshot`s to keep APIs consistent.
public class DualityViewDocReference: Reference {

    // MARK: - Stored properties


    private let _oracledb: FusabaseOracledb
    private var _pathSegments: [String]
    private var _documentId: String
    private let _parent: DualityViewColReference?
    private var _oidGenerated: Bool
    private let _tempId: String
    private let _queryHelper: QueryHelper

    /// Optional version for optimistic concurrency / diagnostics.
    /// Populated from write responses if the backend returns VERSION or _metadata.etag.
    private var _version: String?

    // Listener manager for DV documents -> DocumentSnapshot events
    private lazy var listenerManager: ListenerManager<DualityViewDocReference, DocumentSnapshot> = {
        return ListenerManager(oradb: self._oracledb, ref: self)
    }()

    // MARK: - Public getters (Swift-Doc)

    /// The Oracledb instance associated with this document reference.
    public var oracledb: FusabaseOracledb { _oracledb }

    /// The full path to this DV document using slash separators.
    ///
    /// Examples:
    /// - "dv_name"
    /// - "dv_name/OID"
    public var path: String { _pathSegments.joined(separator: "/") }

    /// The path segments of this DV document.
    ///
    /// Examples:
    /// - ["dv_name"]
    /// - ["dv_name", "OID"]
    var pathSegments: [String] { _pathSegments }

    /// The document identifier.
    ///
    /// - If the OID has been generated by the database, this is the OID value.
    /// - If not yet generated, this is a temporary ID used until the real OID is assigned.
    public var documentId: String { _documentId }

    /// Version/etag tracked for this DV document reference, if available.
    public var version: String? { _version }

    /// The parent DV collection reference, or `nil` if not applicable.
    public var parent: DualityViewColReference? { _parent }

    /// Indicates whether the document OID has already been generated by the database.
    var oidGenerated: Bool { _oidGenerated }

    /// Temporary ID used before the actual OID is generated by the database.
    var tempId: String { _tempId }

    // MARK: - Initializer

    /// Creates a reference to a duality view document in the database.
    ///
    /// The initializer supports both references with OID (existing documents) and
    /// references without OID (new documents that will receive an OID on first write).
    ///
    /// - Parameters:
    ///   - oracledb: The database instance this document belongs to.
    ///   - path: A DV path with 1 or 2 segments, e.g. `"dv_name"` or `"dv_name/OID"`.
    ///   - oidGenerated: Whether the document ID (OID) is already generated by the server.
    /// - Precondition: `path` must contain at most two segments.
    init(oracledb: FusabaseOracledb, path: String, oidGenerated: Bool) {
        self._oracledb = oracledb
        var tokens = path.split(separator: "/").map { String($0) }
        if tokens.count > 2 {
            fatalError("DualityViewDocReference cannot have path with more than 2 segments.")
        }

        self._oidGenerated = oidGenerated
        self._tempId = oidGenerated ? (tokens.last ?? "") : "BAAS_DOC_TEMP_ID=\(UUID().uuidString)"

        // Compute document id and parent path
        if oidGenerated {
            // remove last -> becomes collection path
            let docId = tokens.isEmpty ? "" : tokens.removeLast()
            self._documentId = docId
        } else {
            self._documentId = _tempId
        }

        // parent DV collection if there is at least dv_name segment
        if tokens.isEmpty {
            self._parent = nil
        } else {
            self._parent = DualityViewColReference(oracledb: oracledb, path: tokens.joined(separator: "/"))
        }

        // Assemble final path segments
        self._pathSegments = tokens
        self._pathSegments.append(self._documentId)

        self._queryHelper = QueryHelper(options: oracledb.app.options, oradb: oracledb)
    }

    // MARK: - Helpers

    /// Builds the DV request payload used by the backend.
    ///
    /// - Parameter snapshot: Whether to request server-side snapshot processing.
    /// - Returns: A dictionary payload for DV operations.
    private func makePayload(snapshot: Bool) -> [String: Any] {
        var payload = _queryHelper.getDualityViewPathObject(path: self._pathSegments)
        if snapshot {
            payload["snapshot"] = 1
        }
        return payload
    }

    /// Creates a bridge `DocumentReference` corresponding to this DV document.
    ///
    /// This is used to construct `DocumentSnapshot` instances while reusing the
    /// snapshot infrastructure for standard collection documents.
    private func makeStdDocumentReference() -> DocumentReference {
        let colPath = self._pathSegments.first ?? ""
        let colRef = CollectionReference(oracledb: self._oracledb, path: colPath)
        return DocumentReference(oracledb: self._oracledb, path: self.path, parent: colRef)
    }

    // MARK: - CRUD

    /// Adds a new DV document (auto-generated OID on the server) with the provided data.
    ///
    /// On success, if an OID was not previously generated, this method updates
    /// the local reference with the server-generated OID.
    ///
    /// - Parameter data: A dictionary containing the document fields and values.
    /// - Returns: The same `DualityViewDocReference` instance (for chaining).
    /// - Throws: An error if the operation fails.
    @available(macOS 10.15.0, *)
    public func add(_ data: [String: Any]) async throws -> DualityViewDocReference {
        // Use setDocs with overwrite semantics; server generates OID
        let result = try _queryHelper.setDocs(path: self._pathSegments,
                                              data: data,
                                              setOptions: nil,
                                              entityReference: self,
                                              operation: TransactionOperation(beginTrans: 0, endTrans: 0, transactionName: "", options: nil, version: nil))
        if let anyOid = result["OID"] {
            var oidStr: String?
            if let s = anyOid as? String {
                oidStr = s
            } else if let n = anyOid as? NSNumber {
                oidStr = n.stringValue
            } else if let i = anyOid as? Int {
                oidStr = String(i)
            } else if let i64 = anyOid as? Int64 {
                oidStr = String(i64)
            } else if let d = anyOid as? Double {
                // If it's an integer-like double, format without decimal
                if d.rounded(.towardZero) == d {
                    oidStr = String(Int64(d))
                } else {
                    oidStr = String(d)
                }
            } else {
                oidStr = String(describing: anyOid)
            }
            if let oid = oidStr, !_oidGenerated {
                self.updateId(oid)
            }
        }

        // Also propagate optional VERSION or _metadata.etag
        self._version = DualityViewDocReference.extractVersion(from: result) ?? self._version
        return self
    }

    /// Deletes this DV document from the server.
    ///
    /// - Throws: An error if the operation fails.
    @available(macOS 10.15.0, *)
    public func delete() async throws {
        let _ = try _queryHelper.removeDocs(path: self._pathSegments,
                                            entityReference: self,
                                            operation: TransactionOperation(beginTrans: 0, endTrans: 0, transactionName: "", options: nil, version: nil))
    }

    /// Writes the specified data to this DV document.
    ///
    /// If the document does not exist, it is created. If it exists, the data is
    /// written with the provided options:
    /// - If `options` specifies merge, only the provided fields are updated.
    /// - Otherwise, the document is overwritten.
    ///
    /// If an OID was not previously generated, upon success this method updates
    /// the local reference with the server-generated OID.
    ///
    /// - Parameters:
    ///   - data: A dictionary containing the document fields and values.
    ///   - options: Optional `SetOptions` to control merge behavior.
    /// - Throws: An error if the operation fails.
    @available(macOS 10.15.0, *)
    public func set(_ data: [String: Any], options: SetOptions? = nil) async throws {
        let result = try _queryHelper.setDocs(path: self._pathSegments,
                                              data: data,
                                              setOptions: options,
                                              entityReference: self,
                                              operation: TransactionOperation(beginTrans: 0, endTrans: 0, transactionName: "", options: nil, version: nil))
        if let anyOid = result["OID"], !_oidGenerated {
            var oidStr: String?
            if let s = anyOid as? String {
                oidStr = s
            } else if let n = anyOid as? NSNumber {
                oidStr = n.stringValue
            } else if let i = anyOid as? Int {
                oidStr = String(i)
            } else if let i64 = anyOid as? Int64 {
                oidStr = String(i64)
            } else if let d = anyOid as? Double {
                if d.rounded(.towardZero) == d {
                    oidStr = String(Int64(d))
                } else {
                    oidStr = String(d)
                }
            } else {
                oidStr = String(describing: anyOid)
            }
            if let oid = oidStr {
                self.updateId(oid)
            }
        }

        self._version = DualityViewDocReference.extractVersion(from: result) ?? self._version
    }

    /// Updates fields of this DV document without overwriting the entire document.
    ///
    /// - Parameter fields: A dictionary of fields to update. Keys may be `String` or `FieldPath`.
    /// - Throws: An error if the operation fails.
    @available(macOS 10.15.0, *)
    public func update(_ fields: [AnyHashable: Any]) async throws {
        let result = try _queryHelper.updateDocs(path: self._pathSegments,
                                            data: fields,
                                            entityReference: self,
                                            operation: TransactionOperation(beginTrans: 0, endTrans: 0, transactionName: "", options: nil, version: nil))

        self._version = DualityViewDocReference.extractVersion(from: result) ?? self._version
    }

    // MARK: - Version parsing

    private static func extractVersion(from result: [String: Any]) -> String? {
        if let meta = result["_metadata"] as? [String: Any], let etag = meta["etag"] {
            return extractFlexibleString(etag)
        }
        return extractFlexibleString(result["VERSION"] ?? result["version"])
    }

    private static func extractFlexibleString(_ value: Any?) -> String? {
        guard let value else { return nil }
        if let s = value as? String { return s }
        if let i = value as? Int { return String(i) }
        if let i64 = value as? Int64 { return String(i64) }
        if let n = value as? NSNumber {
            if CFGetTypeID(n) == CFBooleanGetTypeID() { return nil }
            return n.stringValue
        }
        if let d = value as? Double {
            if d.rounded(.towardZero) == d { return String(Int64(d)) }
            return String(d)
        }
        return String(describing: value)
    }

    /// Updates fields of this DV document using alternating field/value parameters.
    ///
    /// Example:
    /// ```
    /// try await docRef.update(field: "name", value: "Alice", "age", 30)
    /// ```
    ///
    /// - Parameters:
    ///   - field: The first field to update.
    ///   - value: The new value for the first field.
    ///   - moreFieldsAndValues: Additional field/value pairs.
    /// - Throws: An error if the operation fails or if parameter pairs are invalid.
    @available(macOS 10.15.0, *)
    public func update(field: String, value: Any?, _ moreFieldsAndValues: Any...) async throws {
        var data: [String: Any?] = [field: value]
        if moreFieldsAndValues.count % 2 != 0 {
            fatalError("Uneven number of field-value pairs.")
        }
        var idx = 0
        while idx < moreFieldsAndValues.count {
            guard let key = moreFieldsAndValues[idx] as? String else {
                fatalError("Field names must be strings.")
            }
            data[key] = moreFieldsAndValues[idx + 1]
            idx += 2
        }
        // compact map nils out
        try await update(data.compactMapValues { $0 })
    }

    /// Updates fields of this DV document using `FieldPath` keys.
    ///
    /// Example:
    /// ```
    /// try await docRef.update(fieldPath: FieldPath("address.city"), value: "Paris")
    /// ```
    ///
    /// - Parameters:
    ///   - fieldPath: The first field path to update.
    ///   - value: The new value for the first field path.
    ///   - moreFieldsAndValues: Additional `FieldPath`/value pairs.
    /// - Throws: An error if the operation fails or if parameter pairs are invalid.
    @available(macOS 10.15.0, *)
    public func update(fieldPath: FieldPath, value: Any?, _ moreFieldsAndValues: Any...) async throws {
        var data: [AnyHashable: Any?] = [fieldPath: value]
        if moreFieldsAndValues.count % 2 != 0 {
            fatalError("Uneven number of field-value pairs.")
        }
        var idx = 0
        while idx < moreFieldsAndValues.count {
            guard let key = moreFieldsAndValues[idx] as? FieldPath else {
                fatalError("Field must be of type FieldPath.")
            }
            data[key] = moreFieldsAndValues[idx + 1]
            idx += 2
        }
        try await update(data.compactMapValues { $0 })
    }

    // MARK: - Reads

    /// Fetches the document snapshot from Oracledb with the default source (`.default`).
    ///
    /// - Returns: A `DocumentSnapshot` for this DV document. Returns an empty snapshot if the document does not exist.
    /// - Throws: An error if the fetch operation fails.
    @available(macOS 10.15.0, *)
    public func get() async throws -> DocumentSnapshot {
        return try await get(source: .default)
    }

    /// Fetches the document snapshot from Oracledb with the provided source.
    ///
    /// Internally, this composes a DV payload, executes a fetch via `QueryHelper`,
    /// and translates the response into a `DocumentSnapshot`. If the document is
    /// not found, an empty snapshot is returned.
    ///
    /// - Parameters:
    ///   - source: The desired fetch source. Currently used for API parity; server selection is not altered.
    ///   - snapshot: Whether to request server-side snapshot processing (optional, default false).
    /// - Returns: A `DocumentSnapshot` for this DV document, or an empty snapshot if the document does not exist.
    /// - Throws: An error if the fetch operation fails.
    @available(macOS 10.15.0, *)
    public func get(source: OracledbSource, snapshot: Bool = false) async throws -> DocumentSnapshot {
        let result = try _queryHelper.fetchDocs(path: self._pathSegments,
                                                payload: makePayload(snapshot: snapshot),
                                                operation: TransactionOperation(beginTrans: 0, endTrans: 0, transactionName: "", options: nil, version: nil))

        // Parse result: expected { ret: [ { osons: { ... } }, ... ] }
        let stdDocRef = makeStdDocumentReference()
        let metadata = SnapshotMetadata(fromCache: false, hasPendingWrites: false)

        if let retArr = result["ret"] as? [[String: Any]],
           let first = retArr.first,
           let osons = first["osons"] as? [String: Any] {
            OracledbLogger.debug("DV get() received osons: \(osons)")
            OracledbLogger.debug("returning snapshot with osons data!!")
            return DocumentSnapshot(data: osons, docRef: stdDocRef, metadata: metadata)
        }

        // Not found -> empty snapshot; explicitly mark exists=false
        return DocumentSnapshot(data: nil, docRef: stdDocRef, metadata: metadata, exists: false)
    }

    // MARK: - Listeners

    // Closure-backed adapter to turn a closure into an EventListener<DocumentSnapshot> for DV docs.
    private final class DVDocumentClosureListener: EventListener {
        typealias T = DocumentSnapshot
        private let onEventBlock: (DocumentSnapshot?, Error?) -> Void

        init(_ onEvent: @escaping (DocumentSnapshot?, Error?) -> Void) {
            self.onEventBlock = onEvent
        }

        func onEvent(_ value: DocumentSnapshot?, _ error: Error?) {
            onEventBlock(value, error)
        }
    }

    /// Adds a snapshot listener that is executed on the main thread by default.
    ///
    /// - Parameter listener: The listener that will receive snapshot updates or errors.
    /// - Returns: A `ListenerRegistration` that can be used to remove the listener.
    func addSnapshotListener(_ listener: any EventListener<DocumentSnapshot>) -> ListenerRegistration {
        let options = SnapshotListenOptions.Builder()
            .build()
        return addSnapshotListener(options, listener)
    }

    /// Adds a snapshot listener that executes callbacks on the specified executor.
    ///
    /// - Parameters:
    ///   - executor: The executor used to run the listener callbacks.
    ///   - listener: The listener that will receive snapshot updates or errors.
    /// - Returns: A `ListenerRegistration` that can be used to remove the listener.
    func addSnapshotListener(executor: Executor,
                                    _ listener: any EventListener<DocumentSnapshot>) -> ListenerRegistration {
        // Executor is ignored; delivery defaults to main thread internally.
        let options = SnapshotListenOptions.Builder()
            .build()
        return addSnapshotListener(options, listener)
    }

    /// Adds a snapshot listener with a metadata changes policy.
    ///
    /// - Parameters:
    ///   - metadataChanges: Whether metadata-only changes should trigger events.
    ///   - listener: The listener that will receive snapshot updates or errors.
    /// - Returns: A `ListenerRegistration` that can be used to remove the listener.
    func addSnapshotListener(metadataChanges: MetadataChanges,
                                    _ listener: any EventListener<DocumentSnapshot>) -> ListenerRegistration {
        let options = SnapshotListenOptions.Builder()
            .setMetadataChanges(metadataChanges)
            .build()
        return addSnapshotListener(options, listener)
    }

    /// Adds a snapshot listener using the specified options.
    ///
    /// - Parameters:
    ///   - options: The snapshot listen options (executor, metadata changes, etc.).
    ///   - listener: The listener that will receive snapshot updates or errors.
    /// - Returns: A `ListenerRegistration` that can be used to remove the listener.
    func addSnapshotListener(_ options: SnapshotListenOptions,
                                    _ listener: any EventListener<DocumentSnapshot>) -> ListenerRegistration {
        return listenerManager.registerListener(listener, options: options)
    }

    // MARK: Public closure-based listener registration (no EventListener in public API)

    /// Registers a listener for this DV document with a simple toggle for metadata change notifications.
    ///
    /// - Parameters:
    ///   - includeMetadataChanges: When `true`, metadata-only changes will trigger callbacks.
    ///   - listener: A closure invoked with the latest `DocumentSnapshot` or an error.
    /// - Returns: A `ListenerRegistration` that can be used to remove the listener.
    func addSnapshotListener(includeMetadataChanges: Bool, listener: @escaping (DocumentSnapshot?, (any Error)?) -> Void) -> any ListenerRegistration {
        let options = SnapshotListenOptions.Builder()
            .setMetadataChanges(includeMetadataChanges ? .include : .exclude)
            .build()
        return addSnapshotListener(options, DVDocumentClosureListener(listener))
    }

    /// Registers a listener for this DV document using the provided `SnapshotListenOptions`.
    ///
    /// - Parameters:
    ///   - options: Listener configuration (executor, metadata change delivery).
    ///   - listener: A closure invoked with the latest `DocumentSnapshot` or an error.
    /// - Returns: A `ListenerRegistration` that can be used to remove the listener.
    func addSnapshotListener(options: SnapshotListenOptions, listener: @escaping (DocumentSnapshot?, (any Error)?) -> Void) -> any ListenerRegistration {
        let wrapped = DVDocumentClosureListener(listener)
        return addSnapshotListener(options, wrapped)
    }

    // MARK: - Equality

    /// Determines whether this DV document reference is equal to another.
    ///
    /// Two references are considered equal if they point to the same database,
    /// have the same path segments, the same parent path (if present), and the same document ID.
    ///
    /// - Parameter other: The other DV document reference to compare.
    /// - Returns: `true` if both references are equal; otherwise, `false`.
    public func isEqual(to other: DualityViewDocReference) -> Bool {
        let sameDb = self.oracledb === other.oracledb
        let samePath = self._pathSegments == other._pathSegments
        let sameParent = (self.parent?.path ?? "") == (other.parent?.path ?? "")
        return sameDb && samePath && sameParent && self._documentId == other._documentId
    }

    // MARK: - ID/Path maintenance

    /// Indicates whether the OID for this document has not yet been generated by the server.
    ///
    /// - Returns: `true` if the OID has not been generated; otherwise, `false`.
    func isOidNotGenerated() -> Bool { return !_oidGenerated }

    /// Updates the local reference with a newly generated OID.
    ///
    /// This method sets the `documentId`, flips `oidGenerated` to `true`, and ensures
    /// the path segments include the new OID in the last position.
    ///
    /// - Parameter id: The newly generated OID.
    func updateId(_ id: String) {
        self._oidGenerated = true
        self._documentId = id
        if _pathSegments.count == 1 {
            _pathSegments.append(id)
        } else {
            _pathSegments[_pathSegments.count - 1] = id
        }
    }
}
